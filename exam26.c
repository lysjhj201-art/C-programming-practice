#include <stdio.h>  // 포인터를 이용한 배열의 정렬

void main()
{
    int s[10] = {1, 0, 3, 2, 5, 4, 7, 6, 9, 8};  // 무작위로 넣음
    int tmp;
    int i, k;

    int *p;

    p = s;  // 배열 s의 주소를 포인터 변수 p에 대입

    printf("정렬 전 배열 s: ");
    for(i=0; i<10; i++)  // 정렬 전의 상태로 데이터 10개를 출력.
    {
        printf("%d", *(p+i));  // i 초깃값 0이니 배열에 넣었던 값 순서대로 출력됨.
    }
    printf("\n");

    for(i=0; i<9; i++)  // 9회 반복. 내부 for문으로 비교할 두값 중 첫번째 값의 자리는 s[0]~s[8].
    {
        for(k=i+1; k<10; k++)  // 내부 for문으로 9회, 8회... 1회 반복한다. 비교할 두값 중 두번째 값의 자리는 s[1]~s[9].
        {
            if(*(p+i) > *(p+k))  // p+i의 값이 p+k의 실제 값보다 크면 두 값을 바꾼다.
            {
                tmp = *(p+i);
                *(p+i) = *(p+k);
                *(p+k) = tmp;
            }
        }
    }
    printf("정렬 후 배열 s: ");
    for(i=0; i<10; i++)  // 정렬 후의 상태로 데이터 10개를 출력한다.
    {
        printf("%d", *(p+i));
    }
    printf("\n");
}